/**
 * Writes a development .env with fresh secrets (never commit it). Refuses to overwrite.
 *   pnpm --filter @hungerly/api env:generate
 */
import { generateKeyPairSync, randomBytes } from 'node:crypto';
import { existsSync, writeFileSync } from 'node:fs';

const target = new URL('../.env', import.meta.url);
if (existsSync(target)) {
  console.error('.env already exists; delete it first if you really want new secrets.');
  process.exit(1);
}
const { privateKey, publicKey } = generateKeyPairSync('ed25519');
const oneLine = (pem: string) => pem.trim().replace(/\n/g, '\\n');
const dbPassword = randomBytes(18).toString('base64url');

const lines = [
  '# Generated by scripts/generate-env.ts — development only. Never commit.',
  'NODE_ENV=development',
  'PORT=4000',
  'PUBLIC_BASE_URL=http://localhost:4000',
  `POSTGRES_PASSWORD=${dbPassword}`,
  `DATABASE_URL=postgres://hungerly:${dbPassword}@localhost:5433/hungerly`,
  `JWT_PRIVATE_KEY="${oneLine(privateKey.export({ type: 'pkcs8', format: 'pem' }).toString())}"`,
  `JWT_PUBLIC_KEY="${oneLine(publicKey.export({ type: 'spki', format: 'pem' }).toString())}"`,
  `TOKEN_HASH_SECRET=${randomBytes(32).toString('base64url')}`,
  `FIELD_ENCRYPTION_KEY=${randomBytes(32).toString('base64')}`,
  '# Development sign-in: codes are printed in the API log. Optionally also accept a fixed code:',
  '# OTP_DEV_FIXED_CODE=123456',
  '# RazorpayX (test keys = sandbox). Leave unset to keep payouts disabled.',
  '# RAZORPAYX_KEY_ID=rzp_test_xxx',
  '# RAZORPAYX_KEY_SECRET=xxx',
  '# RAZORPAYX_ACCOUNT_NUMBER=xxx',
  '# RAZORPAYX_WEBHOOK_SECRET=xxx',
  '',
];
writeFileSync(target, lines.join('\n'), { mode: 0o600 });
console.warn('Wrote apps/api/.env');
